from pathlib import Path
from typing import Dict
import logging

from ap_common import copy_file
from ap_common.constants import NORMALIZED_HEADER_FILENAME

from .matching import (
    find_matching_dark,
    find_matching_bias,
    find_candidate_flat_dates,
)

logger = logging.getLogger(__name__)


def check_masters_exist(
    date_dir: Path,
    light_metadata: Dict[str, str],
    scale_darks: bool = False,
) -> Dict[str, bool]:
    """
    Check if masters matching a light already exist in date directory.

    Runs the same match queries used against the library, non-recursively
    on date_dir. Flats match on everything except date, so a flat from any
    date (e.g. chosen interactively on an earlier run) counts.

    Args:
        date_dir: Directory to check for existing masters
        light_metadata: Metadata dictionary for light frame
        scale_darks: Allow shorter exposure darks, as for the library search

    Returns:
        Dict with has_dark, has_bias, has_flat boolean flags
    """
    if not date_dir.is_dir():
        return {"has_dark": False, "has_bias": False, "has_flat": False}

    return {
        "has_dark": find_matching_dark(
            date_dir, light_metadata, scale_darks=scale_darks, recursive=False
        )
        is not None,
        "has_bias": find_matching_bias(date_dir, light_metadata, recursive=False)
        is not None,
        "has_flat": bool(
            find_candidate_flat_dates(date_dir, light_metadata, recursive=False)
        ),
    }


def copy_master_to_blink(
    master_metadata: Dict[str, str],
    dest_dir: Path,
    dry_run: bool = False,
) -> bool:
    """
    Copy master calibration frame to blink directory.

    Args:
        master_metadata: Metadata dict for master frame (includes 'filename')
        dest_dir: Destination directory (DATE directory)
        dry_run: If True, log action but don't copy

    Returns:
        True if copied (or would be copied in dry-run), False if skipped
    """
    source_path = Path(master_metadata[NORMALIZED_HEADER_FILENAME])
    dest_path = dest_dir / source_path.name

    if dest_path.exists():
        logger.debug(f"Master already exists, skipping: {dest_path.name}")
        return False

    if dry_run:
        logger.debug(f"[DRY-RUN] Would copy: {source_path.name} -> {dest_dir}")
        return True

    logger.debug(f"Copying: {source_path.name} -> {dest_dir}")
    copy_file(str(source_path), str(dest_path))
    return True
