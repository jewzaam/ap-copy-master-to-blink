def _resolve(path, dir_fd):
    """Resolve path, honoring dir_fd as shutil.rmtree passes it on Linux."""
    path = Path(path)
    if dir_fd is not None and not path.is_absolute():
        path = Path(os.readlink(f"/proc/self/fd/{dir_fd}")) / path
    return path.resolve()


